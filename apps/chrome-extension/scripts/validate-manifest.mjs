import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const source = JSON.parse(await readFile(new URL("../manifest.json", import.meta.url), "utf8"));
assert.equal(source.manifest_version, 3);
assert.deepEqual([...source.permissions].sort(), ["activeTab", "contextMenus", "scripting", "storage"]);
assert.equal("host_permissions" in source, false);
for (const forbidden of ["history", "bookmarks", "downloads", "clipboardRead", "cookies", "webRequest", "nativeMessaging", "<all_urls>"]) assert.equal(JSON.stringify(source).includes(forbidden), false);
assert.equal(source.background.type, "module");
assert.match(source.content_security_policy.extension_pages, /script-src 'self'/);
console.log("Manifest V3 validation passed.");
